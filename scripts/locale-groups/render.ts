/**
 * The message group list, written from the catalog files in
 * `src/locales/en/`. Edge has no folder access, so the list is generated
 * into source and the type stays a literal union.
 */

import { sortStrings } from "#fp";

export const MESSAGE_GROUPS_FILE = "src/locales/message-groups.generated.ts";

const CATALOG = /^([a-z0-9-]+)\.json$/;

/** The group a catalog file name names. Anything else in the folder is a
 * mistake, so it fails loudly. */
const groupOf = (fileName: string): string => {
  const group = CATALOG.exec(fileName)?.[1];
  if (group === undefined) {
    throw new Error(`Not a message catalog: src/locales/en/${fileName}`);
  }
  return group;
};

/** The text of the generated file for these catalog file names. */
export const messageGroupsSource = (fileNames: readonly string[]): string =>
  [
    "// Generated by `deno task locales:generate` from src/locales/en/. Do not edit.",
    "",
    "export const MESSAGE_GROUPS = [",
    ...sortStrings(fileNames.map(groupOf)).map((group) => `  "${group}",`),
    "] as const;",
    "",
    "export type MessageGroup = (typeof MESSAGE_GROUPS)[number];",
    "",
  ].join("\n");
